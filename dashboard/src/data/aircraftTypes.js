/** Retourne la fiche du type pour un code (insensible à la casse), ou null. */
export function findAircraftType(code) {
  const c = String(code || '').trim().toUpperCase()
  if (!c) return null
  return AIRCRAFT_TYPES.find(t => t.code === c) || null
}
